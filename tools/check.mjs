#!/usr/bin/env node
// Repository checks.
//
// Run from the repository root:
//   node tools/check.mjs

import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { access, readFile, readdir } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const failures = [];
const notes = [];

function fail(message) {
  failures.push(message);
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === '.git' || entry.name === 'node_modules'
      || entry.name === '.opencode' || entry.name === '_site') {
      continue;
    }
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else files.push(path);
  }
  return files;
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

function isGenerated(text) {
  const head = text.split('\n', 4).join('\n');
  return /generated by|@generated/i.test(head);
}

function checkLineLimit(files) {
  for (const path of files) {
    if (!/\.(js|mjs|css)$/.test(path)) continue;
    const relativePath = relative(ROOT, path);
    if (relativePath.includes('/data/')) continue;

    const text = textOf(path);
    if (isGenerated(text)) continue;
    text.split('\n').forEach((line, index) => {
      if (line.length > 80) {
        fail(relativePath + ':' + (index + 1) + ' exceeds 80 columns');
      }
    });
  }
}

const fileCache = new Map();
function textOf(path) {
  if (!fileCache.has(path)) fileCache.set(path, '');
  return fileCache.get(path);
}

async function loadText(path) {
  const text = await readFile(path, 'utf8');
  fileCache.set(path, text);
  return text;
}

function checkSyntax(files) {
  for (const path of files) {
    if (!/\.(js|mjs)$/.test(path)) continue;
    const result = spawnSync(
      process.execPath,
      ['--experimental-default-type=module', '--check', path],
      { encoding: 'utf8' }
    );
    if (result.status !== 0) {
      fail(relative(ROOT, path) + ' has a syntax error: '
        + (result.stderr || '').split('\n')[0]);
    }
  }
}

async function checkRequiredFiles() {
  // Runtime entry points only. Other source modules are covered by
  // checkLocalImports, and docs, tools, and workflows do not run the app.
  // Keep this list small; see docs/internal/checks.md.
  const required = [
    'index.html',
    'src/main.js',
    'src/styles/app.css',
    'src/keyboard/data/base.csv',
  ];

  for (const path of required) {
    if (!await exists(resolve(ROOT, path))) fail('missing ' + path);
  }

  // The app has no dependencies, and manifests are generated, not committed.
  const forbidden = [
    'package.json', 'package-lock.json', 'node_modules',
    'plugins/keymaps/manifest.json',
    'plugins/themes/manifest.json',
    'plugins/layouts/manifest.json',
  ];
  for (const path of forbidden) {
    if (await exists(resolve(ROOT, path))) {
      fail('unexpected path exists: ' + path);
    }
  }
}

async function checkHtml() {
  const path = resolve(ROOT, 'index.html');
  if (!await exists(path)) return;
  const html = await loadText(path);

  const ids = [
    'keyboard', 'list', 'legend', 'legendSwitch', 'facetGroup', 'colourGroup',
    'legendBand', 'search',
    'bindingSearch', 'searchReset', 'keymapIntro', 'boardNone', 'keyFilter',
    'fileInput', 'board', 'side',
    'leftColumn', 'keymapSelect', 'instructions', 'importBtn',
    'layerSwitch', 'dropText', 'metaSelect', 'themeSelect', 'layoutSelect',
    'colourSelect',
    'controlsToggle', 'controlsToggleLabel', 'keymapControlsBody',
    'clearFiltersBtn', 'clearBtn', 'resetAppBtn', 'notice', 'resultStatus',
  ];
  for (const id of ids) {
    if (!html.includes('id="' + id + '"')) fail('index.html is missing #' + id);
  }
  if (!/src="src\/main\.js"/.test(html)) fail('index.html needs src/main.js');
  if (!/href="src\/styles\/app\.css"/.test(html)) {
    fail('index.html needs the external app stylesheet');
  }
  if (/<style[\s>]/i.test(html)) {
    fail('index.html should not contain inline styles');
  }
  if (/\sstyle=/i.test(html)) {
    fail('index.html should not use style attributes');
  }
  if (!/Content-Security-Policy/.test(html)) {
    fail('index.html needs a Content-Security-Policy meta tag');
  }
  if (/<script(?![^>]*\bsrc=)/i.test(html)) {
    fail('index.html should not use inline scripts under the CSP');
  }
}

// Every relative import under src/ and tools/ must point at a real file.
async function checkLocalImports() {
  const files = [
    ...await walk(resolve(ROOT, 'src')),
    ...await walk(resolve(ROOT, 'tools')),
  ];
  for (const file of files) {
    if (!/\.(js|mjs)$/.test(file)) continue;
    const text = await readFile(file, 'utf8');
    const specifiers = [
      ...text.matchAll(/\bfrom\s+['"]([^'"]+)['"]/g),
      ...text.matchAll(/^\s*import\s+['"]([^'"]+)['"]/gm),
    ].map(match => match[1]);
    for (const specifier of specifiers) {
      if (!specifier.startsWith('.')) continue;
      if (!await exists(resolve(dirname(file), specifier))) {
        fail(relative(ROOT, file) + ' imports missing ' + specifier);
      }
    }
  }
}

async function checkPluginApiImports(directory, label) {
  const files = await walk(directory);
  for (const file of files) {
    if (!/\.(js|mjs)$/.test(file)) continue;
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
      const specifier = match[1];
      if (specifier.includes('/src/')
        && !specifier.endsWith('/src/plugin-api.js')) {
        fail(label + ' imports non-public helper ' + specifier);
      }
      if (/(^|\/)plugins\//.test(specifier)) {
        fail(label + ' imports another plugin ' + specifier);
      }
    }
  }
}

async function checkKeymapPlugin(id) {
  const label = 'plugins/keymaps/' + id;
  const directory = resolve(ROOT, 'plugins/keymaps', id);
  for (const file of ['index.js', 'source.json']) {
    if (!await exists(resolve(directory, file))) {
      fail(label + ' is missing ' + file);
    }
  }
  if (id === 'base') fail(label + ' is a built-in keymap, not a plugin');

  const sourcePath = resolve(directory, 'source.json');
  if (await exists(sourcePath)) {
    const source = JSON.parse(await readFile(sourcePath, 'utf8'));
    if (source.id !== id) fail(label + ' source.json id mismatch');
    if (!source.license) fail(label + ' source.json needs a license');

    if (source.source !== undefined && source.source !== null
      && typeof source.source !== 'string') {
      fail(label + ' source must be a string or null');
    }
    if (!source.output) fail(label + ' needs an output path');
    if (!source.outputSha) fail(label + ' needs an output hash');

    const dataPath = resolve(directory, source.output || '');
    if (await exists(dataPath)) {
      const data = await readFile(dataPath, 'utf8');
      if (sha256(data) !== source.outputSha) {
        fail(label + ' data hash does not match source.json');
      }
    } else {
      fail(label + ' data file is missing');
    }
  }

  const indexText = await readFile(resolve(directory, 'index.js'), 'utf8');
  if (!/defineKeymapPlugin\s*\(/.test(indexText)) {
    fail(label + ' must use defineKeymapPlugin');
  }
  await checkPluginApiImports(directory, label);
}

async function checkKeymapPlugins() {
  const root = resolve(ROOT, 'plugins/keymaps');
  const entries = await readdir(root, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.isDirectory()) await checkKeymapPlugin(entry.name);
  }
}

async function checkThemeCss(path, required, label) {
  const css = await readFile(path, 'utf8');
  const defined = new Set(
    [...css.matchAll(/--([a-z0-9-]+)\s*:/g)].map(match => match[1])
  );
  for (const variable of required) {
    if (!defined.has(variable)) {
      fail(label + ' is missing --' + variable);
    }
  }
  if (!/color-scheme\s*:/.test(css)) {
    fail(label + ' needs color-scheme');
  }
}

async function themeVariables() {
  const source = await readFile(
    resolve(ROOT, 'src/theme/contract.js'),
    'utf8'
  );
  const list = source.match(
    /export const THEME_VARIABLES = Object\.freeze\(\[([\s\S]*?)\]\);/
  );
  const required = list
    ? [...list[1].matchAll(/'([^']+)'/g)].map(match => match[1])
    : [];
  if (!required.length) fail('could not read THEME_VARIABLES');
  return required;
}

async function checkThemePlugin(id, required) {
  const label = 'plugins/themes/' + id;
  const directory = resolve(ROOT, 'plugins/themes', id);
  const requiredFiles = ['index.js', 'theme.css', 'source.json'];
  for (const file of requiredFiles) {
    if (!await exists(resolve(directory, file))) {
      fail(label + ' is missing ' + file);
    }
  }
  if (['system', 'light', 'dark'].includes(id)) {
    fail(label + ' is a built-in theme, not a plugin');
  }

  const sourcePath = resolve(directory, 'source.json');
  if (await exists(sourcePath)) {
    const source = JSON.parse(await readFile(sourcePath, 'utf8'));
    if (source.id !== id) fail(label + ' source.json id mismatch');
    if (!source.license) fail(label + ' source.json needs a license');
  }
  const indexText = await readFile(resolve(directory, 'index.js'), 'utf8');
  if (!/defineThemePlugin\s*\(/.test(indexText)) {
    fail(label + ' must use defineThemePlugin');
  }
  await checkThemeCss(
    resolve(directory, 'theme.css'),
    required,
    label
  );
  await checkPluginApiImports(directory, label);
}

async function checkThemes() {
  const root = resolve(ROOT, 'plugins/themes');
  const entries = await readdir(root, { withFileTypes: true });
  const required = await themeVariables();
  const directories = entries
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name);

  for (const id of ['light', 'dark']) {
    const cssPath = resolve(ROOT, 'src/theme/builtin', id + '.css');
    if (!await exists(cssPath)) {
      fail('src/theme/builtin/' + id + '.css is missing');
      continue;
    }
    await checkThemeCss(cssPath, required, 'src/theme/builtin/' + id + '.css');
    if (directories.includes(id)) {
      fail('built-in theme must not live in plugins/themes/' + id);
    }
  }

  for (const id of directories) {
    await checkThemePlugin(id, required);
  }
}

async function checkLayoutPlugin(id) {
  const label = 'plugins/layouts/' + id;
  const directory = resolve(ROOT, 'plugins/layouts', id);
  for (const file of ['index.js', 'source.json']) {
    if (!await exists(resolve(directory, file))) {
      fail(label + ' is missing ' + file);
    }
  }
  if (id === 'ansi-us') {
    fail(label + ' is the built-in layout, not a plugin');
  }
  const sourcePath = resolve(directory, 'source.json');
  if (await exists(sourcePath)) {
    const source = JSON.parse(await readFile(sourcePath, 'utf8'));
    if (source.id !== id) fail(label + ' source.json id mismatch');
    if (!source.license) fail(label + ' source.json needs a license');
  }
  const indexText = await readFile(resolve(directory, 'index.js'), 'utf8');
  if (!/defineLayoutPlugin\s*\(/.test(indexText)) {
    fail(label + ' must use defineLayoutPlugin');
  }
  await checkPluginApiImports(directory, label);
}

async function checkLayouts() {
  const root = resolve(ROOT, 'plugins/layouts');
  const entries = await readdir(root, { withFileTypes: true });
  const builtinRoot = resolve(ROOT, 'src/keyboard/builtin');
  const builtinModule = resolve(builtinRoot, 'ansi-us.js');
  const builtinSource = resolve(builtinRoot, 'ansi-us.source.json');

  if (!await exists(builtinModule)) {
    fail('src/keyboard/builtin/ansi-us.js is missing');
  }
  if (!await exists(builtinSource)) {
    fail('src/keyboard/builtin/ansi-us.source.json is missing');
  } else {
    const source = JSON.parse(await readFile(builtinSource, 'utf8'));
    if (!source.license) {
      fail('src/keyboard/builtin/ansi-us needs a source license');
    }
  }
  if (await exists(resolve(root, 'ansi-us'))) {
    fail('built-in layout must not live in plugins/layouts/ansi-us');
  }

  for (const entry of entries) {
    if (entry.isDirectory()) await checkLayoutPlugin(entry.name);
  }
}

// Locked public surface; see
// docs/public/reference/plugin-contract.md#api-surface.
const PLUGIN_API_EXPORTS = [
  'PLUGIN_API_VERSION',
  'defineKeymapPlugin',
  'defineThemePlugin',
  'defineLayoutPlugin',
  'THEME_VARIABLES',
  'LAYOUT_KEY_IDS',
  'LAYOUT_VARIANTS',
  'entryKey',
  'mergeOverrides',
  'removeEntries',
  'MODIFIER_TOKENS',
  'isModifierToken',
  'normalizeKeyName',
  'normalizeModifier',
  'splitPlusCombo',
  'uniqueTokens',
];

function collectApiExports(text) {
  const names = [];
  for (const match of text.matchAll(/export const ([A-Za-z0-9_]+)/g)) {
    names.push(match[1]);
  }
  for (const match of text.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of match[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop().trim();
      if (name) names.push(name);
    }
  }
  return names;
}

async function checkPluginApi() {
  const text = await loadText(resolve(ROOT, 'src/plugin-api.js'));
  const actual = collectApiExports(text);
  const duplicates = actual.filter(
    (name, index) => actual.indexOf(name) !== index
  );
  for (const name of new Set(duplicates)) {
    fail('plugin-api.js exports ' + name + ' twice');
  }
  for (const name of actual) {
    if (!PLUGIN_API_EXPORTS.includes(name)) {
      fail('plugin-api.js exports undocumented ' + name);
    }
  }
  for (const name of PLUGIN_API_EXPORTS) {
    if (!actual.includes(name)) {
      fail('plugin-api.js no longer exports ' + name);
    }
  }
}

async function checkCoreBoundary() {
  const directories = [
    resolve(ROOT, 'src/core'),
    resolve(ROOT, 'src/keyboard'),
    resolve(ROOT, 'src/theme'),
    resolve(ROOT, 'src/lib'),
  ];
  for (const directory of directories) {
    const files = await walk(directory);
    for (const file of files) {
      if (!/\.js$/.test(file)) continue;
      const text = await readFile(file, 'utf8');
      for (const match of text.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
        const specifier = match[1];
        if (/(^|\/)(keymaps|plugins|themes|layouts)\//.test(specifier)) {
          fail(relative(ROOT, file) + ' imports concrete ' + specifier);
        }
      }
      if (/\blocalStorage\b/.test(text)) {
        fail(relative(ROOT, file) + ' still uses localStorage');
      }
      if (/\bstyle\s*=\s*["']/.test(text) || /\.style\./.test(text)) {
        fail(relative(ROOT, file) + ' writes inline styles');
      }
    }
  }

  const srcFiles = await walk(resolve(ROOT, 'src'));
  for (const file of srcFiles) {
    if (!/\.js$/.test(file)) continue;
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
      if (/(^|\/)plugins\//.test(match[1])) {
        fail(relative(ROOT, file) + ' imports a concrete plugin');
      }
    }
  }
}

async function pluginDirectories(type) {
  const root = resolve(ROOT, 'plugins', type);
  if (!await exists(root)) return [];
  const entries = await readdir(root, { withFileTypes: true });
  return entries
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name);
}

async function checkCoreNeutrality() {
  const pluginIds = [];
  for (const type of ['keymaps', 'themes', 'layouts']) {
    pluginIds.push(...await pluginDirectories(type));
  }
  const files = [
    ...await walk(resolve(ROOT, 'src/core')),
    ...await walk(resolve(ROOT, 'src/keyboard')),
    ...await walk(resolve(ROOT, 'src/theme')),
    ...await walk(resolve(ROOT, 'src/lib')),
    resolve(ROOT, 'src/plugin-api.js'),
  ];

  for (const file of files) {
    if (!/\.js$/.test(file)) continue;
    const text = await readFile(file, 'utf8');
    for (const id of pluginIds) {
      if (new RegExp('\\b' + id + '\\b', 'i').test(text)) {
        fail(relative(ROOT, file) + ' references concrete plugin ' + id);
      }
    }
  }
}

async function checkWorkflows() {
  const ci = await readFile(
    resolve(ROOT, '.github/workflows/ci.yml'),
    'utf8'
  );
  const pages = await readFile(
    resolve(ROOT, '.github/workflows/pages.yml'),
    'utf8'
  );
  const updates = await readFile(
    resolve(ROOT, '.github/workflows/update-keymap-plugins.yml'),
    'utf8'
  );

  if (!ci.includes('tools/check.mjs')) {
    fail('ci.yml is missing tools/check.mjs');
  }
  if (!/needs:\s*checks/.test(pages)) {
    fail('pages.yml must depend on the checks job');
  }
  if (!/tools\/stage-site\.mjs/.test(pages)) {
    fail('pages.yml must use tools/stage-site.mjs');
  }
  if (!/tools\/update-keymap-plugin\.mjs/.test(updates)) {
    fail('update-keymap-plugins.yml must use the keymap update runner');
  }
  if (!/create-pull-request/.test(updates)) {
    fail('update-keymap-plugins.yml must open a pull request');
  }
  if (!/matrix/.test(updates)) {
    fail('update-keymap-plugins.yml must use a keymap matrix');
  }
}

async function checkLinks() {
  const result = spawnSync(
    process.execPath,
    [resolve(ROOT, 'tools/check-links.mjs')],
    { encoding: 'utf8' }
  );
  if (result.status !== 0) {
    fail('link checks failed:\n' + (result.stderr || '').trim());
  } else {
    notes.push(result.stdout.trim());
  }
}

async function checkData() {
  const result = spawnSync(
    process.execPath,
    ['--experimental-default-type=module',
      resolve(ROOT, 'tools/check-data.mjs')],
    { encoding: 'utf8' }
  );
  if (result.status !== 0) {
    fail('data checks failed: ' + (result.stderr || '').trim());
  } else {
    notes.push(result.stdout.trim());
  }
}

async function main() {
  await checkRequiredFiles();
  await checkLocalImports();
  await checkHtml();
  await checkKeymapPlugins();
  await checkThemes();
  await checkLayouts();
  await checkPluginApi();
  await checkCoreBoundary();
  await checkCoreNeutrality();
  await checkWorkflows();
  await checkLinks();

  const files = await walk(ROOT);
  await Promise.all(files.map(loadText));
  checkSyntax(files);
  checkLineLimit(files);
  await checkData();

  if (notes.length) console.log(notes.join('\n'));
  if (failures.length) {
    console.error('check failed with ' + failures.length + ' problem(s):');
    for (const failure of failures) console.error(' - ' + failure);
    process.exitCode = 1;
    return;
  }

  console.log('ok: checks passed for ' + files.length + ' files');
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
